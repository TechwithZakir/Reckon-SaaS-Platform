def pick_language(requested: str | None, cookie: str | None, accept_language: str | None) -> str:
    """``?lang=`` wins, then the remembered cookie, then the browser preference."""
    for candidate in (requested, cookie):
        if candidate in LANGUAGES:
            return candidate
    if accept_language and accept_language.strip().lower().startswith("bn"):
        return "bn"
    return DEFAULT_LANGUAGE


def get_strings(lang: str) -> dict:
    return STRINGS.get(lang) or STRINGS[DEFAULT_LANGUAGE]
